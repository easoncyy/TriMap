type SourceKey = keyof typeof references;
type ModuleName = '视觉感知' | '三维空间理解' | '视觉动作学习' | '闭环视觉控制';
type Card = {
  id: string; title: string; kind: string; module: ModuleName; summary: string;
  definition: string; io: string; principle: string; methods: string;
  use: string; limits: string; evaluation: string; questions: string;
  refs: SourceKey[]; x: number; y: number;
};

function card(c: Card): KnowledgeNode {
  const evidence = c.refs.map(key => {
    const ref = references[key];
    return `${ref.citation} 范围：${ref.scope} 核验情况：${ref.review} 查阅日期：${checkedOn}。 ${ref.url}`;
  }).join('\n');
  return {
    id: c.id, title: c.title, kind: c.kind, lens: 'domain',
    summary: `${c.module}｜${c.summary}`,
    body: [
      `所属模块：${c.module}`, `概念定义：${c.definition}`, `输入与输出：${c.io}`,
      `核心技术原理：${c.principle}`, `代表性方法或模型：${c.methods}`,
      `机器人操作用途：${c.use}`, `技术局限与成立条件：${c.limits}`,
      `评测方式：${c.evaluation}`, `可靠来源与核验：${evidence}`,
      `尚待核实的问题：${c.questions}`,
      '本组状态：内容初稿，未开展本组复现或实机验证；来源初核不等于整张知识卡已核实。',
    ].join('\n\n'),
    sources: c.refs.map(key => references[key].url), status: '待核实', x: c.x, y: c.y,
  };
}

